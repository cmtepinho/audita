import { build } from 'esbuild';
import { mkdir, copyFile, writeFile, rm } from 'node:fs/promises';
await rm('dist',{recursive:true,force:true});
await mkdir('dist/assets',{recursive:true});
await mkdir('.build',{recursive:true});
await build({entryPoints:['src/main.js'],bundle:true,format:'esm',target:['safari16.4'],outfile:'dist/assets/app.js',minify:true,legalComments:'eof'});
await build({entryPoints:['src/domain.ts'],bundle:true,platform:'node',format:'esm',outfile:'.build/domain.mjs'});
await build({entryPoints:['src/sms.ts'],bundle:true,platform:'node',format:'esm',outfile:'.build/sms.mjs'});
await build({entryPoints:['src/report.js'],bundle:true,platform:'node',format:'esm',outfile:'.build/report.mjs'});
await copyFile('index.html','dist/index.html');
await copyFile('app.webmanifest','dist/app.webmanifest');
await copyFile('sw.js','dist/sw.js');
await copyFile('assets/icon.svg','dist/assets/icon.svg');
await copyFile('assets/icon-192.png','dist/assets/icon-192.png');
await copyFile('assets/icon-512.png','dist/assets/icon-512.png');
await mkdir('dist/reference',{recursive:true});
await copyFile('reference/index.original.html','dist/reference/index.original.html');
await copyFile('node_modules/pdfjs-dist/legacy/build/pdf.worker.mjs','dist/assets/pdf.worker.mjs');
await copyFile('node_modules/pdfjs-dist/LICENSE','dist/assets/pdfjs-LICENSE');
await writeFile('dist/.nojekyll','');
console.log('Build local gerado; nenhum documento financeiro incluído.');
